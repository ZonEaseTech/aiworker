// Pick "a" or "an" by the leading sound of the following word so vowel-initial
// soul names ("AIWorker", "Operations") read "an" instead of "a".
function indefiniteArticle(word: string): string {
  return /^[aeiou]/i.test(word.trim()) ? 'an' : 'a'
}

